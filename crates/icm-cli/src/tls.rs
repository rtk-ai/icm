//! HTTPS for `icm serve --http` (`[http.tls]`).
//!
//! The certificate is, in order: `cert` + `key` from the config (a
//! CA-issued or wildcard certificate); `cert.pem` + `key.pem` in `dir`
//! (default `<data dir>/tls`); or, when `dir` holds neither and
//! `self_signed` is on, a self-signed certificate generated there once and
//! reused on later starts, so clients that pinned it keep trusting it.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

use crate::config::TlsConfig;

/// The PEM files the server loads.
#[derive(Debug, Clone, PartialEq)]
pub struct TlsFiles {
    pub cert: PathBuf,
    pub key: PathBuf,
    /// Generated by this start (self-signed).
    pub generated: bool,
}

/// Names a generated certificate always covers.
const LOCAL_NAMES: [&str; 3] = ["localhost", "127.0.0.1", "::1"];

/// `~/x` → `$HOME/x`; anything else unchanged.
fn expand_home(path: &str) -> PathBuf {
    if let Some(rest) = path.strip_prefix("~/")
        && let Some(dirs) = directories::BaseDirs::new()
    {
        return dirs.home_dir().join(rest);
    }
    PathBuf::from(path)
}

/// `<data dir>/tls`, where a generated certificate goes by default.
pub fn default_dir() -> Option<PathBuf> {
    directories::ProjectDirs::from("dev", "icm", "icm").map(|d| d.data_dir().join("tls"))
}

/// The certificate and key to serve, generating a self-signed pair in the
/// directory when the configuration allows it and nothing is there yet.
pub fn resolve(cfg: &TlsConfig, default_dir: Option<PathBuf>) -> Result<TlsFiles> {
    match (cfg.cert.trim(), cfg.key.trim()) {
        ("", "") => {}
        (cert, key) if !cert.is_empty() && !key.is_empty() => {
            let files = TlsFiles {
                cert: expand_home(cert),
                key: expand_home(key),
                generated: false,
            };
            for path in [&files.cert, &files.key] {
                if !path.is_file() {
                    bail!("[http.tls]: {} not found", path.display());
                }
            }
            return Ok(files);
        }
        _ => bail!("[http.tls]: set both `cert` and `key`, or neither"),
    }

    let dir = match cfg.dir.trim() {
        "" => default_dir.context("[http.tls]: no data directory; set `dir`")?,
        dir => expand_home(dir),
    };
    let cert = dir.join("cert.pem");
    let key = dir.join("key.pem");
    match (cert.is_file(), key.is_file()) {
        (true, true) => Ok(TlsFiles {
            cert,
            key,
            generated: false,
        }),
        // Never overwrite half of a pair someone put there.
        (true, false) | (false, true) => bail!(
            "[http.tls]: {} needs both cert.pem and key.pem",
            dir.display()
        ),
        (false, false) if !cfg.self_signed => bail!(
            "[http.tls]: no cert.pem / key.pem in {}; set `cert` and `key`, or `self_signed = true`",
            dir.display()
        ),
        (false, false) => {
            generate(&dir, &cfg.names)?;
            Ok(TlsFiles {
                cert,
                key,
                generated: true,
            })
        }
    }
}

/// Days a generated certificate is valid: long enough not to bother a
/// local setup, short enough that a leaked key does not live forever.
const SELF_SIGNED_DAYS: i64 = 730;

/// Write a self-signed `cert.pem` + `key.pem` for `localhost`, the loopback
/// addresses and `names` into `dir` (the key readable by the owner only).
fn generate(dir: &Path, names: &[String]) -> Result<()> {
    use chrono::Datelike;
    let mut all: Vec<String> = LOCAL_NAMES.iter().map(|s| s.to_string()).collect();
    for name in names {
        let name = name.trim();
        if !name.is_empty() && !all.iter().any(|n| n == name) {
            all.push(name.to_string());
        }
    }
    let mut params = rcgen::CertificateParams::new(all)
        .context("[http.tls]: invalid name for the self-signed certificate")?;
    params
        .distinguished_name
        .push(rcgen::DnType::CommonName, "icm");
    let day = |d: chrono::DateTime<chrono::Utc>| {
        rcgen::date_time_ymd(d.year(), d.month() as u8, d.day() as u8)
    };
    let now = chrono::Utc::now();
    params.not_before = day(now - chrono::Duration::days(1));
    params.not_after = day(now + chrono::Duration::days(SELF_SIGNED_DAYS));
    let key = rcgen::KeyPair::generate().context("[http.tls]: generating a key")?;
    let cert = params
        .self_signed(&key)
        .context("[http.tls]: generating a self-signed certificate")?;
    create_private_dir(dir)?;
    write_new(&dir.join("key.pem"), key.serialize_pem().as_bytes(), 0o600)?;
    write_new(&dir.join("cert.pem"), cert.pem().as_bytes(), 0o644)?;
    Ok(())
}

/// Create `dir` readable by the owner only. A directory that already exists
/// keeps its mode: `dir = "~"` must not lock the home directory.
fn create_private_dir(dir: &Path) -> Result<()> {
    if dir.is_dir() {
        return Ok(());
    }
    std::fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(dir, std::fs::Permissions::from_mode(0o700))
            .with_context(|| format!("restricting {}", dir.display()))?;
    }
    Ok(())
}

/// Write a file that must not exist yet (no following a planted link).
fn write_new(path: &Path, bytes: &[u8], #[allow(unused_variables)] mode: u32) -> Result<()> {
    use std::io::Write;
    let mut options = std::fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(mode);
    }
    let mut file = options
        .open(path)
        .with_context(|| format!("creating {}", path.display()))?;
    file.write_all(bytes)
        .with_context(|| format!("writing {}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("icm-tls-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        dir
    }

    #[test]
    fn a_self_signed_pair_is_generated_once_then_reused() {
        let dir = temp_dir("gen");
        let cfg = TlsConfig {
            dir: dir.display().to_string(),
            names: vec!["icm.example.com".into(), "localhost".into()],
            ..TlsConfig::default()
        };
        let first = resolve(&cfg, None).unwrap();
        assert!(first.generated);
        let pem = std::fs::read_to_string(&first.cert).unwrap();
        assert!(pem.starts_with("-----BEGIN CERTIFICATE-----"));
        assert!(
            std::fs::read_to_string(&first.key)
                .unwrap()
                .contains("PRIVATE KEY")
        );
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(&first.key).unwrap().permissions().mode();
            assert_eq!(mode & 0o777, 0o600);
        }
        let second = resolve(&cfg, None).unwrap();
        assert!(!second.generated);
        assert_eq!(std::fs::read_to_string(&second.cert).unwrap(), pem);
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn configured_files_win_and_must_exist() {
        let dir = temp_dir("cfg");
        std::fs::create_dir_all(&dir).unwrap();
        let cert = dir.join("wild.crt");
        let key = dir.join("wild.key");
        let cfg = TlsConfig {
            cert: cert.display().to_string(),
            key: key.display().to_string(),
            ..TlsConfig::default()
        };
        assert!(
            resolve(&cfg, None)
                .unwrap_err()
                .to_string()
                .contains("not found")
        );
        std::fs::write(&cert, "c").unwrap();
        std::fs::write(&key, "k").unwrap();
        let files = resolve(&cfg, None).unwrap();
        assert_eq!((files.cert, files.key, files.generated), (cert, key, false));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn half_a_configuration_is_refused() {
        let cfg = TlsConfig {
            cert: "/x/cert.pem".into(),
            ..TlsConfig::default()
        };
        assert!(resolve(&cfg, None).is_err());
    }

    #[test]
    fn an_empty_directory_without_self_signed_is_refused() {
        let dir = temp_dir("nogen");
        let cfg = TlsConfig {
            self_signed: false,
            ..TlsConfig::default()
        };
        let err = resolve(&cfg, Some(dir.clone())).unwrap_err().to_string();
        assert!(err.contains("self_signed"));
        assert!(!dir.exists());
    }

    #[test]
    fn half_a_pair_in_the_directory_is_never_overwritten() {
        let dir = temp_dir("half");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("cert.pem"), "mine").unwrap();
        let cfg = TlsConfig::default();
        assert!(resolve(&cfg, Some(dir.clone())).is_err());
        assert_eq!(
            std::fs::read_to_string(dir.join("cert.pem")).unwrap(),
            "mine"
        );
        let _ = std::fs::remove_dir_all(&dir);
    }
}
